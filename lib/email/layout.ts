import { escapeHtml, plainText, singleLine } from "./html"

export const EMAIL_PRODUCT_NAME = "Billing & Revenue Portal"

export type EmailBrand = {
  portalName?: string | null
  companyName?: string | null
  logoUrl?: string | null
  supportEmail?: string | null
  year?: number
}

export function emailDocument(input: {
  preheader: string
  brand: EmailBrand
  heading: string
  introHtml: string
  bodyHtml?: string
  accent?: "default" | "success"
}) {
  const brand = normalizeBrand(input.brand)
  const accent = input.accent === "success" ? "#047857" : "#1d4ed8"

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta http-equiv="Content-Type" content="text/html; charset=UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${escapeHtml(input.heading)}</title>
</head>
<body style="margin:0;padding:0;background:#eef2f6;">
  <div style="display:none;max-height:0;overflow:hidden;mso-hide:all;">${escapeHtml(plainText(input.preheader))}</div>
  <table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="background:#eef2f6;">
    <tr>
      <td align="center" style="padding:24px 12px;">
        <table role="presentation" width="600" cellpadding="0" cellspacing="0" style="width:100%;max-width:600px;background:#ffffff;border:1px solid #d9e2ec;">
          ${emailHeader(brand)}
          <tr>
            <td style="height:4px;background:${accent};font-size:0;line-height:0;">&nbsp;</td>
          </tr>
          <tr>
            <td style="padding:28px 32px 8px;font-family:Arial,Helvetica,sans-serif;color:#0f172a;">
              <h1 style="margin:0 0 16px;font-size:22px;line-height:1.3;font-weight:700;">${escapeHtml(singleLine(input.heading))}</h1>
              ${input.introHtml}
            </td>
          </tr>
          ${input.bodyHtml ? `<tr><td style="padding:0 32px 8px;font-family:Arial,Helvetica,sans-serif;color:#334155;font-size:15px;line-height:1.6;">${input.bodyHtml}</td></tr>` : ""}
          ${emailFooter(brand)}
        </table>
      </td>
    </tr>
  </table>
</body>
</html>`
}

export function emailHeader(brand: EmailBrand) {
  const value = normalizeBrand(brand)
  const logo = value.logoUrl
    ? `<img src="${escapeHtml(value.logoUrl)}" alt="${escapeHtml(value.companyName)}" width="36" height="36" style="display:block;border:0;outline:none;text-decoration:none;">`
    : ""
  const company = value.companyName !== value.portalName
    ? `<p style="margin:4px 0 0;font-family:Arial,Helvetica,sans-serif;font-size:12px;line-height:1.4;color:#cbd5e1;">${escapeHtml(value.companyName)}</p>`
    : ""

  return `<tr>
    <td style="padding:20px 32px;background:#0f172a;">
      <table role="presentation" cellpadding="0" cellspacing="0">
        <tr>
          ${logo ? `<td style="padding-right:12px;vertical-align:middle;">${logo}</td>` : ""}
          <td style="vertical-align:middle;">
            <p style="margin:0;font-family:Arial,Helvetica,sans-serif;font-size:13px;line-height:1.4;font-weight:700;letter-spacing:0.04em;color:#ffffff;">${escapeHtml(value.portalName.toUpperCase())}</p>
            ${company}
          </td>
        </tr>
      </table>
    </td>
  </tr>`
}

export function emailFooter(brand: EmailBrand) {
  const value = normalizeBrand(brand)
  const assistance = value.supportEmail
    ? `For assistance, contact <a href="mailto:${escapeHtml(value.supportEmail)}" style="color:#1d4ed8;text-decoration:none;">${escapeHtml(value.supportEmail)}</a>.`
    : "For assistance, please contact your system administrator."

  return `<tr>
    <td style="padding:20px 32px;background:#f8fafc;border-top:1px solid #e2e8f0;font-family:Arial,Helvetica,sans-serif;font-size:12px;line-height:1.6;color:#64748b;">
      <p style="margin:0 0 8px;color:#0f172a;font-weight:700;">${escapeHtml(value.portalName)}</p>
      <p style="margin:0 0 8px;">This is an automated notification generated by the ${escapeHtml(value.portalName)}.</p>
      <p style="margin:0 0 8px;">&copy; ${value.year} ${escapeHtml(value.companyName)}. All rights reserved.</p>
      <p style="margin:0;">${assistance}</p>
    </td>
  </tr>`
}

export function emailButton(href: string, label: string) {
  const url = safeHttpUrl(href)
  const text = singleLine(label) || "Open"
  if (!url) return ""

  return `<table role="presentation" cellpadding="0" cellspacing="0" style="margin:8px 0 20px;">
    <tr>
      <td bgcolor="#1d4ed8" style="background:#1d4ed8;">
        <a href="${escapeHtml(url)}" style="display:inline-block;padding:12px 22px;font-family:Arial,Helvetica,sans-serif;font-size:14px;line-height:1;font-weight:700;color:#ffffff;text-decoration:none;">${escapeHtml(text)}</a>
      </td>
    </tr>
  </table>`
}

export function emailInfoTable(rows: Array<{ label: string; value: string }>) {
  const body = rows
    .filter((row) => row.value.trim())
    .map(
      (row) => `<tr>
        <td style="padding:8px 12px;border-bottom:1px solid #e2e8f0;font-family:Arial,Helvetica,sans-serif;font-size:13px;color:#64748b;width:160px;">${escapeHtml(singleLine(row.label))}</td>
        <td style="padding:8px 12px;border-bottom:1px solid #e2e8f0;font-family:Arial,Helvetica,sans-serif;font-size:14px;color:#0f172a;font-weight:700;">${escapeHtml(singleLine(row.value))}</td>
      </tr>`,
    )
    .join("")

  if (!body) return ""

  return `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="margin:4px 0 20px;border:1px solid #e2e8f0;border-bottom:0;">${body}</table>`
}

export function emailSecurityNotice(text: string) {
  return `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="margin:4px 0 8px;">
    <tr>
      <td style="padding:12px 14px;background:#f8fafc;border-left:3px solid #0f172a;font-family:Arial,Helvetica,sans-serif;font-size:13px;line-height:1.5;color:#334155;">
        <strong style="color:#0f172a;">Security notice</strong><br>
        ${escapeHtml(plainText(text))}
      </td>
    </tr>
  </table>`
}

export function emailParagraphs(paragraphs: string[]) {
  return paragraphs
    .map(
      (paragraph) =>
        `<p style="margin:0 0 16px;font-family:Arial,Helvetica,sans-serif;font-size:15px;line-height:1.6;color:#334155;">${escapeHtml(plainText(paragraph)).replace(/\n/g, "<br>")}</p>`,
    )
    .join("")
}

export function absoluteAssetUrl(path: string | null | undefined, base: string) {
  const value = path?.trim() || ""
  if (!value || !base) return null
  if (value.startsWith("http://") || value.startsWith("https://")) return safeHttpUrl(value)
  if (!value.startsWith("/") || value.startsWith("//") || value.includes("\\")) return null
  return safeHttpUrl(`${base}${value}`)
}

function normalizeBrand(brand: EmailBrand) {
  const portalName = singleLine(brand.portalName || "") || EMAIL_PRODUCT_NAME
  const companyName = singleLine(brand.companyName || "") || portalName
  return {
    portalName,
    companyName,
    logoUrl: brand.logoUrl ? safeHttpUrl(brand.logoUrl) : null,
    supportEmail: safeEmail(brand.supportEmail),
    year: brand.year ?? new Date().getFullYear(),
  }
}

function safeHttpUrl(value: string) {
  try {
    const url = new URL(value)
    if (url.protocol !== "http:" && url.protocol !== "https:") return null
    return url.toString()
  } catch {
    return null
  }
}

function safeEmail(value: string | null | undefined) {
  const email = value?.trim() || ""
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) return null
  return email
}
